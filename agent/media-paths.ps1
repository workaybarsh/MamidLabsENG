# External image and video model files (used in place, without copying).
#
# "Import local model" used to copy the chosen file under ComfyUI\models;
# for a 13 GB Krea-2 file this both took minutes and left a second copy on disk.
# Now the file path is written to the externalMediaModels list in settings\api.json
# and ComfyUI sees those folders through settings\comfy-extra-models.yaml
# (--extra-model-paths-config). The model name is just the file name.
#
# This file has no UI: the desktop, the install script (configure-models.ps1) and
# the image/video jobs use the same functions.

# Supported architectures: Krea 2 Turbo for images (.safetensors, or .gguf for Lite),
# Wan 2.2 TI2V 5B for video (.safetensors). Different architectures need different workflows.
function Test-MediaModelFile([string]$path, [string]$kind) {
    $name = [IO.Path]::GetFileName($path)
    if ($kind -eq 'image') { return $name -match '(?i)krea2.*turbo.*\.(safetensors|gguf)$' }
    if ($kind -eq 'video') { return $name -match '(?i)wan2[._]2.*ti2v.*5b.*\.safetensors$' }
    return $false
}

# The folder kind where ComfyUI will look for the model: GGUFs go to unet, where ComfyUI-GGUF
# looks, the others to diffusion_models.
function Get-ComfyModelFolder([string]$path) {
    if ([IO.Path]::GetExtension($path).ToLowerInvariant() -eq '.gguf') { return 'unet' }
    return 'diffusion_models'
}

function Read-ExternalMediaModels([string]$root) {
    $path = Join-Path $root 'settings\api.json'
    if (!(Test-Path -LiteralPath $path -PathType Leaf)) { return @() }
    try { $settings = Get-Content -LiteralPath $path -Raw -Encoding UTF8 | ConvertFrom-Json } catch { return @() }
    return @($settings.externalMediaModels | Where-Object { $_ -and $_.path })
}

# Adds a new external model to the list (the same path is not added twice) and returns
# the updated list. The file and the architecture are validated here.
function Add-ExternalMediaModel($models, [string]$path, [string]$kind) {
    if (!(Test-Path -LiteralPath $path -PathType Leaf)) { throw "Model file not found: $path" }
    if (!(Test-MediaModelFile $path $kind)) {
        $expected = if ($kind -eq 'image') { 'Krea 2 Turbo (.safetensors or .gguf)' } else { 'Wan 2.2 TI2V 5B (.safetensors)' }
        throw "This file is not supported. Expected: $expected."
    }
    $full = [IO.Path]::GetFullPath($path)
    $list = @($models | Where-Object { $_ -and [string]$_.path -ne $full })
    return @($list + @(@{ kind = $kind; path = $full }))
}

# Generates the settings\comfy-extra-models.yaml file from the list. If the content has not
# changed the file is not touched: ComfyUI is restarted if the file is newer, and an unnecessary
# restart wastes ~20 s. If the list is empty the file is deleted. Returns the written path.
function Write-ComfyExtraModelPaths([string]$root, $models) {
    $yaml = Join-Path $root 'settings\comfy-extra-models.yaml'
    $folders = [ordered]@{}
    foreach ($model in @($models)) {
        if (!$model -or !(Test-Path -LiteralPath ([string]$model.path) -PathType Leaf)) { continue }
        $key = Get-ComfyModelFolder ([string]$model.path)
        $dir = ([IO.Path]::GetDirectoryName([IO.Path]::GetFullPath([string]$model.path))).Replace('\', '/')
        if (!$folders.Contains($key)) { $folders[$key] = [Collections.Generic.List[string]]::new() }
        if (!$folders[$key].Contains($dir)) { $folders[$key].Add($dir) }
    }
    if (!$folders.Count) {
        if (Test-Path -LiteralPath $yaml) { Remove-Item -LiteralPath $yaml -Force }
        return $null
    }
    $lines = [Collections.Generic.List[string]]::new()
    $lines.Add('# Generated by MamidLabs; change it from the Image and video models window.')
    $lines.Add('mamidlabs_external:')
    foreach ($key in $folders.Keys) {
        $lines.Add("    ${key}: |")
        foreach ($dir in $folders[$key]) { $lines.Add("        $dir") }
    }
    $content = ($lines -join "`n") + "`n"
    [void][IO.Directory]::CreateDirectory((Split-Path -Parent $yaml))
    if ((Test-Path -LiteralPath $yaml) -and ([IO.File]::ReadAllText($yaml) -eq $content)) { return $yaml }
    [IO.File]::WriteAllText($yaml, $content, [Text.UTF8Encoding]::new($false))
    return $yaml
}

# If the model name is not under ComfyUI\models it is looked up among the registered external
# files. If found, the name to give ComfyUI (the file name) is returned; otherwise $null.
function Resolve-ExternalMediaModel([string]$root, [string]$name, [string]$comfyFolder) {
    if (!$name -or $name.IndexOfAny([IO.Path]::GetInvalidFileNameChars()) -ge 0) { return $null }
    foreach ($model in @(Read-ExternalMediaModels $root)) {
        $path = [string]$model.path
        if ([IO.Path]::GetFileName($path) -ne $name) { continue }
        if ((Get-ComfyModelFolder $path) -ne $comfyFolder) { continue }
        if (Test-Path -LiteralPath $path -PathType Leaf) { return $name }
    }
    return $null
}
